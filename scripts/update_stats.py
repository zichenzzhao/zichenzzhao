# ---------------------------------------------------------------- helpers
def git(repo, *args, env=None):
    r = subprocess.run(["git", "-C", repo] + list(args), capture_output=True, text=True,
                       errors="replace", env=env)
    return r.stdout if r.returncode == 0 else ""


def now_et():
    try:
        from zoneinfo import ZoneInfo
        return datetime.datetime.now(ZoneInfo("America/New_York"))
    except Exception:
        return datetime.datetime.now()


def fmt(n):
    return format(n, ",")


def lang_of(path):
    base = os.path.basename(path).lower()
    if base == "dockerfile":
        return "Docker"
    return LANG.get(os.path.splitext(base)[1])


def classify(path, name, gen=()):
    if any(re.search(v, path) for v in VENDORED.get(name, [])):
        return "vendored"
    if EXCLUDE_DIRS.search(path):
        return "excluded_dir"
    if EXCLUDE_FILES.search(path):
        return "data_or_binary"
    if path in gen:
        return "generated"
    lang = lang_of(path)
    if lang is None:
        return "other"
    if lang in NON_CODE:
        return "docs_config"
    if lang == "Jupyter":
        return "notebook"
    return "code"


def load_json(p, default):
    try:
        return json.load(open(p))
    except Exception:
        return default


def script_hash():
    h = hashlib.sha256(open(os.path.abspath(__file__), "rb").read())
    h.update(json.dumps(load_json(ACK_FILE, {}), sort_keys=True).encode())
    return h.hexdigest()[:16]


